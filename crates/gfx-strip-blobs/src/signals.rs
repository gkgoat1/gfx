//! Content signals (plan §5.2 knob 4): deterministic "looks generated"
//! fingerprints, judged on a bounded scan window (default 64 KiB prefix).
//!
//! The rule table is deliberately explicit and per-signal toggleable — the
//! heuristic must be reviewable, not folk wisdom. Defaults are conservative
//! per plan §8: banner + lockfile + minification fingerprints on, the
//! experimental compact-word heuristic off.

use alloc::vec::Vec;

/// Which signal fired (report surface).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Signal {
    /// A known lockfile/registry manifest fingerprint.
    Lockfile(LockfileKind),
    /// "Generated code" banner markers (GitHub-Linguist-style subset).
    GeneratedBanner,
    /// Minification fingerprint: huge lines with almost no whitespace.
    Minified,
    /// Experimental Linguist-style compact-word dominance. Off by default.
    CompactWords,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum LockfileKind {
    Cargo,
    Npm,
    Yarn,
    Poetry,
    RubyGems,
    Composer,
    Gradle,
    CocoaPods,
}

impl LockfileKind {
    #[allow(dead_code)]
    fn name(self) -> &'static str {
        match self {
            LockfileKind::Cargo => "Cargo.lock",
            LockfileKind::Npm => "package-lock.json",
            LockfileKind::Yarn => "yarn.lock",
            LockfileKind::Poetry => "poetry.lock",
            LockfileKind::RubyGems => "Gemfile.lock",
            LockfileKind::Composer => "composer.lock",
            LockfileKind::Gradle => "gradle.lockfile",
            LockfileKind::CocoaPods => "Podfile.lock",
        }
    }
}

/// Content-signal configuration.
#[derive(Clone, Debug)]
pub struct ContentSignals {
    /// Judge at most this many leading bytes (default 64 KiB).
    pub scan_cap: usize,
    /// Lockfile/registry fingerprints (default on).
    pub lockfile_markers: bool,
    /// Generated-code banners (default on).
    pub generated_banner: bool,
    /// Minification fingerprint (default on).
    pub minified: bool,
    /// Experimental compact-word heuristic (default off, plan §5.2).
    pub compact_words: bool,
}

impl Default for ContentSignals {
    fn default() -> Self {
        ContentSignals {
            scan_cap: 64 * 1024,
            lockfile_markers: true,
            generated_banner: true,
            minified: true,
            compact_words: false,
        }
    }
}

/// Banner markers, ASCII-case-insensitive, searched within the scan window.
const BANNERS: &[&[u8]] = &[
    b"do not edit",
    b"autogenerated",
    b"auto-generated",
    b"generated by",
    b"@generated",
    b"@nolint",
    b"code generated",
];

/// Lockfile starts-with markers. Checked against the leading bytes of the
/// payload (after optional UTF-8 BOM). JSON manifests use a content marker
/// inside the first scan window instead of ordering assumptions.
const LOCK_PREFIXES: &[(&[u8], LockfileKind)] = &[
    (b"# This file is automatically @generated by Cargo", LockfileKind::Cargo),
    (b"# This file is automatically @generated by Poetry", LockfileKind::Poetry),
    (b"# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT.", LockfileKind::Yarn),
    (b"# This is a Gradle generated file for dependency locking.", LockfileKind::Gradle),
    (b"GEM\n", LockfileKind::RubyGems),
    (b"PODS:\n", LockfileKind::CocoaPods),
];

/// JSON-manifest content markers (searched, since key order is not fixed).
const LOCK_JSON_MARKERS: &[(&[u8], LockfileKind)] = &[
    (b"\"lockfileVersion\"", LockfileKind::Npm),
    (b"\"content-hash\"", LockfileKind::Composer),
];

impl ContentSignals {
    /// Every signal off (CLI opt-in posture: the library default enables
    /// the conservative set, the composed binary asks for it explicitly).
    pub fn all_off() -> Self {
        ContentSignals {
            lockfile_markers: false,
            generated_banner: false,
            minified: false,
            compact_words: false,
            ..ContentSignals::default()
        }
    }

    /// Judge a payload; `Some(signal)` means "treat as generated".
    pub fn judge(&self, data: &[u8]) -> Option<Signal> {
        if data.is_empty() {
            return None;
        }
        let window = &data[..data.len().min(self.scan_cap)];

        if self.lockfile_markers {
            // Skip a UTF-8 BOM for prefix checks.
            let head = window.strip_prefix(b"\xef\xbb\xbf").unwrap_or(window);
            for (prefix, kind) in LOCK_PREFIXES {
                if head.starts_with(prefix) {
                    return Some(Signal::Lockfile(*kind));
                }
            }
            if window.starts_with(b"{") {
                for (marker, kind) in LOCK_JSON_MARKERS {
                    if contains_ascii(window, marker) {
                        return Some(Signal::Lockfile(*kind));
                    }
                }
            }
        }

        if self.generated_banner {
            for b in BANNERS {
                if contains_ascii_case_insensitive(window, b) {
                    return Some(Signal::GeneratedBanner);
                }
            }
        }

        if self.minified && looks_minified(window) {
            return Some(Signal::Minified);
        }

        if self.compact_words && looks_compact_words(window) {
            return Some(Signal::CompactWords);
        }

        None
    }
}

/// ASCII-case-insensitive substring search (bytes ≥ 0x80 are never matched
/// by a marker, so lossy folding is exact here).
fn contains_ascii_case_insensitive(hay: &[u8], needle: &[u8]) -> bool {
    if needle.is_empty() || hay.len() < needle.len() {
        return false;
    }
    let mut lowered = Vec::with_capacity(hay.len());
    for &b in hay {
        lowered.push(b.to_ascii_lowercase());
    }
    let needle: Vec<u8> = needle.iter().map(|b| b.to_ascii_lowercase()).collect();
    lowered
        .windows(needle.len())
        .any(|w| w == needle.as_slice())
}

fn contains_ascii(hay: &[u8], needle: &[u8]) -> bool {
    if needle.is_empty() || hay.len() < needle.len() {
        return false;
    }
    hay.windows(needle.len()).any(|w| w == needle)
}

/// Minification fingerprint (documented rule): at least one line longer
/// than 4096 bytes whose whitespace ratio (space/tab/newline/CR bytes over
/// all bytes) is under 2%. Source maps are absent in this signal; bundles
/// without `.map` are exactly the long-low-whitespace case.
fn looks_minified(window: &[u8]) -> bool {
    let mut line_start = 0usize;
    for (i, &b) in window.iter().enumerate() {
        if b == b'\n' {
            let line = &window[line_start..i];
            if line.len() > 4096 {
                let ws = line
                    .iter()
                    .filter(|&&c| c == b' ' || c == b'\t' || c == b'\r')
                    .count();
                if (ws as f64) / (line.len() as f64) < 0.02 {
                    return true;
                }
            }
            line_start = i + 1;
        }
    }
    // Tail line (unterminated within the window).
    let line = &window[line_start..];
    line.len() > 4096 && {
        let ws = line
            .iter()
            .filter(|&&c| c == b' ' || c == b'\t' || c == b'\r' || c == b'\n')
            .count();
        (ws as f64) / (line.len() as f64) < 0.02
    }
}

/// Experimental compact-word heuristic (plan §5.2, off by default):
/// dominant lines whose content is mostly long alphanumeric tokens — the
/// Linguist-style "this text has no prose structure" proxy. Documented
/// deterministic rule: ≥ 3 non-empty lines each containing ≥ 5 alphanumeric
/// runs of length ≥ 12.
fn looks_compact_words(window: &[u8]) -> bool {
    let mut dominant = 0u32;
    let mut line_start = 0usize;
    for (i, &b) in window.iter().enumerate() {
        if b == b'\n' || i + 1 == window.len() {
            let line = &window[line_start..=if b == b'\n' { i - 1 } else { i }];
            line_start = i + 1;
            let mut tokens = 0u32;
            let mut run = 0usize;
            for &c in line {
                if c.is_ascii_alphanumeric() || c == b'_' {
                    run += 1;
                } else {
                    if run >= 12 {
                        tokens += 1;
                    }
                    run = 0;
                }
            }
            if run >= 12 {
                tokens += 1;
            }
            if tokens >= 5 {
                dominant += 1;
                if dominant >= 3 {
                    return true;
                }
            }
        }
    }
    false
}

#[cfg(test)]
mod tests {
    use super::*;
    use alloc::vec;

    #[test]
    fn banners_fire_case_insensitively() {
        let cs = ContentSignals::default();
        assert_eq!(
            cs.judge(b"// Generated by the protocol compiler. DO NOT EDIT!\nfn main() {}\n"),
            Some(Signal::GeneratedBanner)
        );
        // Documented conservative default (plan §8): the bare marker
        // matches anywhere in the scan window, hand-written or not; hosts
        // opt out per-signal or via protect_globs.
        assert_eq!(
            cs.judge(b"// hand-written, do not edit me please\n"),
            Some(Signal::GeneratedBanner)
        );
        assert_eq!(cs.judge(b"@generated\n"), Some(Signal::GeneratedBanner));
    }

    #[test]
    fn lockfile_prefixes() {
        let cs = ContentSignals::default();
        assert_eq!(
            cs.judge(b"# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 3\n"),
            Some(Signal::Lockfile(LockfileKind::Cargo))
        );
        assert_eq!(
            cs.judge(b"# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT.\n# yarn lockfile v1\n"),
            Some(Signal::Lockfile(LockfileKind::Yarn))
        );
        assert_eq!(
            cs.judge(b"{\n  \"name\": \"x\",\n  \"lockfileVersion\": 3,\n}\n"),
            Some(Signal::Lockfile(LockfileKind::Npm))
        );
        assert_eq!(cs.judge(b"{\"random\": 1}\n"), None);
    }

    #[test]
    fn minification_fingerprint() {
        let cs = ContentSignals::default();
        let mut blob = Vec::new();
        blob.extend_from_slice(b"function ok(){return 1}\n");
        blob.extend(&vec![b'a'; 8192]);
        assert_eq!(cs.judge(&blob), Some(Signal::Minified));

        let mut spaced = Vec::new();
        spaced.extend(vec![b'a'; 8192]);
        // 10% whitespace: below the length bar is not enough.
        for chunk in spaced.chunks_mut(10) {
            chunk[0] = b' ';
        }
        assert_eq!(cs.judge(&spaced), None, "10% whitespace is not minified");
    }

    #[test]
    fn scan_cap_bounds_work() {
        let cs = ContentSignals {
            scan_cap: 16,
            ..ContentSignals::default()
        };
        let mut blob = vec![b'x'; 64];
        blob[40..51].copy_from_slice(b"DO NOT EDIT");
        assert_eq!(cs.judge(&blob), None, "marker beyond scan cap is invisible");
    }

    #[test]
    fn compact_words_off_by_default() {
        let cs = ContentSignals::default();
        let long_line = "abcdefghijklmnop qrs0123456789 tuvwxy012345 zzzz0123456789 aaaabbbb0000 cccc0123456789\n".repeat(5);
        assert_eq!(cs.judge(long_line.as_bytes()), None);
        let cs_on = ContentSignals {
            compact_words: true,
            ..ContentSignals::default()
        };
        assert_eq!(cs_on.judge(long_line.as_bytes()), Some(Signal::CompactWords));
    }

    #[test]
    fn all_off_means_no_verdict() {
        let cs = ContentSignals {
            lockfile_markers: false,
            generated_banner: false,
            minified: false,
            compact_words: false,
            ..ContentSignals::default()
        };
        assert_eq!(cs.judge(b"# This file is automatically @generated by Cargo\n"), None);
    }
}
